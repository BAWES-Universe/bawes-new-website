export type PixelIconName = keyof typeof ICONS

const RUNS = Object.fromEntries(
  Object.entries(ICONS).map(([k, v]) => [k, encodeRuns(v)])
) as Record<PixelIconName, ReturnType<typeof encodeRuns>>

export default function PixelIcon({
  name,
  colors,
  size = 40,
  className = '',
}: {
  name: PixelIconName
  colors: [string, string, string, string]
  size?: number
  className?: string
}) {
  const map: Record<string, string> = { '1': colors[0], '2': colors[1], '3': colors[2], '4': colors[3] }
  return (
    <svg width={size} height={size} viewBox="0 0 16 16" className={className} aria-hidden="true" shapeRendering="crispEdges">
      {RUNS[name].map((r, i) => (
        <rect key={i} x={r.x} y={r.y} width={r.w} height={1} fill={map[r.key]} />
      ))}
    </svg>
  )
}
